import json
import os
import shutil
import subprocess
from pathlib import Path

# Same defaults as `appearance` in the shell config (services/Config.qml).
DEFAULT_COLOR = "#6750a4"
DEFAULT_MODE = "dark"
DEFAULT_VARIANT = "tonal-spot"


def state_dir() -> Path:
    base = os.environ.get("XDG_STATE_HOME") or Path.home() / ".local" / "state"
    return Path(base) / "kirin"


class SchemeService:
    """Writes the colour scheme files the shell and Hyprland read.

    Produces the same files as the shell's Scheme service:
    scheme.json (for Quickshell) and colors.lua (for Hyprland).
    """

    def __init__(self, directory: Path | None = None) -> None:
        self._dir = directory or state_dir()

    @property
    def json_path(self) -> Path:
        return self._dir / "scheme.json"

    @property
    def lua_path(self) -> Path:
        return self._dir / "colors.lua"

    def exists(self) -> bool:
        return self.json_path.is_file() and self.lua_path.is_file()

    def create_default(self, force: bool = False) -> bool:
        """Generates the default scheme. Returns False if one already exists."""
        if self.exists() and not force:
            return False

        self.write(self.generate(DEFAULT_COLOR, DEFAULT_MODE, DEFAULT_VARIANT), DEFAULT_COLOR, DEFAULT_MODE, DEFAULT_VARIANT)
        return True

    def generate(self, color: str, mode: str, variant: str) -> dict[str, str]:
        if shutil.which("matugen") is None:
            raise RuntimeError("matugen is not installed")

        result = subprocess.run(
            ["matugen", "color", "hex", color, "--dry-run", "-q", "-j", "hex", "-m", mode, "-t", f"scheme-{variant}"],
            capture_output=True,
            text=True,
            check=True,
        )
        colors = json.loads(result.stdout)["colors"]
        # With -m set, "default" holds the requested mode.
        return {name: value["default"]["color"] for name, value in colors.items()}

    def write(self, colors: dict[str, str], color: str, mode: str, variant: str) -> None:
        self._dir.mkdir(parents=True, exist_ok=True)

        # Must match the shell's JSON.stringify of its inputs, key order included,
        # so the shell recognises what this scheme was made from.
        inputs = json.dumps(
            {"source": "color", "image": "", "color": color, "mode": mode, "variant": variant},
            separators=(",", ":"),
        )
        self.json_path.write_text(json.dumps({"inputs": inputs, "colors": colors}, indent=2) + "\n")

        lua = "\n".join(f'  {name} = "{hex_[1:]}",' for name, hex_ in colors.items())
        self.lua_path.write_text(f"-- Generated by kirin from scheme.json. Do not edit.\nreturn {{\n{lua}\n}}\n")
